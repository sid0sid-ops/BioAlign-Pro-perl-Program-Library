#!/usr/bin/perl
# Concatenation
$string1 = "potato";
$string2 = "head";
$newstring = $string1 . $string2; # results in "potatohead"
print "$newstring\n";

# Repeat Operation
$newstring = "t" x 5; # results in "ttttt"
print "$newstring\n";

# Increment
$stringvar = "abc";
$stringvar++; # results in "abd"
print "$stringvar\n";
